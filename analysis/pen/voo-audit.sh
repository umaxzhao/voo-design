#!/bin/bash
# Read-only capability audit of the VOO Design repo for GAPS-vs-VOO.md.
# Each line: <capability-key>\t<pattern>\t<count>\t<first-3 files>
cd "$(dirname "$0")/../.." || exit 1
audit() {
  local key="$1"; local pat="$2"
  local files count
  files=$(grep -rlE --include='*.js' --include='*.jsx' --include='*.cjs' --include='*.mjs' -- "$pat" src electron 2>/dev/null)
  count=$(printf '%s\n' "$files" | grep -c . )
  printf '%-28s | %-58s | %3s | %s\n' "$key" "$pat" "$count" "$(printf '%s\n' "$files" | head -3 | paste -sd, -)"
}
