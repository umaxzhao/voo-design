#!/usr/bin/env node
/**
 * Writes the Google Fonts index the editor loads from.
 *
 * Reads the public family metadata Google publishes for fonts.google.com and
 * keeps, for each family, its category and the upright weights it ships. The
 * output is committed, so the editor never needs the catalogue at runtime; only
 * the font files are fetched, on demand, from fonts.googleapis.com.
 *
 * Usage: node scripts/generate-google-fonts-index.mjs
 */

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const METADATA_URL = "https://fonts.google.com/metadata/fonts";
const OUTPUT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/canvas/editor/google_fonts_index.js",
);

async function fetchMetadata() {
  const response = await fetch(METADATA_URL);
  if (!response.ok) throw new Error(`metadata request failed: ${response.status}`);
  // Google prefixes the JSON with a guard line that is not valid JSON.
  const text = (await response.text()).replace(/^\)\]\}'\s*/, "");
  const { familyMetadataList } = JSON.parse(text);
  if (!Array.isArray(familyMetadataList)) throw new Error("unexpected metadata shape");
  return familyMetadataList;
}

function uprightWeights(family) {
  return Object.keys(family.fonts ?? {})
    .map(Number)
    .filter((weight) => Number.isFinite(weight))
    .sort((a, b) => a - b);
}

const families = (await fetchMetadata())
  .map((family) => ({
    family: family.family,
    category: family.category,
    weights: uprightWeights(family),
  }))
  .filter((entry) => entry.family && entry.weights.length > 0)
  .sort((a, b) => a.family.localeCompare(b.family));

const rows = families
  .map((entry) => `  [${JSON.stringify(entry.family)}, ${JSON.stringify(entry.category)}, ${JSON.stringify(entry.weights.join(","))}],`)
  .join("\n");

const source = `// Generated by scripts/generate-google-fonts-index.mjs. Do not edit by hand.
// Each row: [family, category, upright weights].

export const GOOGLE_FONT_INDEX = [
${rows}
];

const INDEX_BY_FAMILY = new Map(GOOGLE_FONT_INDEX.map(([family, , weights]) => [family, weights]));

/** Whether Google publishes this family, so the editor can load it on demand. */
export function isGoogleFamily(family) {
  return INDEX_BY_FAMILY.has(family);
}

/** The css2 weight spec for a family, e.g. ":wght@400;700", or "" when unknown. */
export function googleWeightSpecOf(family) {
  const weights = INDEX_BY_FAMILY.get(family);
  return weights ? \`:wght@\${weights.split(",").join(";")}\` : "";
}
`;

await writeFile(OUTPUT, source);
console.log(`wrote ${families.length} families to ${path.relative(process.cwd(), OUTPUT)}`);
