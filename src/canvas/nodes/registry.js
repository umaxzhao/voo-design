/** Node types that were deleted outright and must be dropped on migration. */
export const REMOVED_NODE_TYPES = new Set([
  "brandCapsule",
  "templateCapsule",
  // The Storyboard and 3D editors were removed with their node types.
  "storyboard",
  "model3dAsset",
]);

/** Returns the registry entry for a node type; throws for unknown types. */
export function getNodeTypeDefinition(type) {
  const entry = NODE_TYPE_REGISTRY[type];
  if (!entry) throw new Error(`Unknown node type: ${type}`);
  return entry;
}
