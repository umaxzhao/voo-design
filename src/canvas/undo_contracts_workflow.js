function workflowAction(
  actionId,
  userAction,
  boundary,
  source,
  {
    requiresHistoryWriter = true,
    indirectHistoryCall = null,
    indirectHistoryCallCount = 0,
    delegatesTo = null,
    owner = "local",
  } = {},
) {
  return Object.freeze({
    actionId,
    domain: "workflow",
    userAction,
    boundary,
    expectedEntries: 1,
    noOpEntries: 0,
    pendingEntries: boundary === "async-final" ? 0 : null,
    progressEntries: boundary === "async-final" ? 0 : null,
    failureEntries: 0,
    requiresHistoryWriter,
    indirectHistoryCall,
    indirectHistoryCallCount,
    delegatesTo,
    owner,
    source,
  });
}

