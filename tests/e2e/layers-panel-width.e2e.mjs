import assert from "node:assert/strict";
import { withEditorBrowser } from "./editor-browser-fixture.mjs";

await withEditorBrowser(async ({ page, tool }) => {
  const panel = page.getByTestId("editor-layers-panel");
  const handle = page.getByTestId("editor-layers-resize");
  await panel.waitFor();
  assert.equal(await handle.count(), 1, "Layers needs an edge resize handle");
  await page.evaluate(() => {
    const editor = window.__vooEditor;
    editor.setDoc({ ...editor.getDocument(), nodes: [{ id: "long-layer", kind: "rect", name: "Product settings / notification preferences / long layer name", visible: true, x: 0, y: 0, width: 100, height: 80, fill: "#ffffff" }] });
    editor.selectExactly(["long-layer"]);
  });
  const name = panel.locator("#layer-row-long-layer button").filter({ hasText: "Product settings / notification preferences / long layer name" });
  await name.waitFor();
  const initialNameWidth = await name.evaluate(element => element.clientWidth);
  const originalDocument = await page.evaluate(() => window.__vooEditor.serialise());
  const start = await panel.boundingBox();
  const grip = await handle.boundingBox();
  const drag = async delta => {
    const box = await handle.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width / 2 + delta, box.y + box.height / 2, { steps: 8 });
    await page.mouse.up();
  };
  assert.ok(Math.abs(grip.x + grip.width / 2 - start.x - start.width) < 10);
  await drag(140);
  let resized = await panel.boundingBox();
  assert.ok(Math.abs(resized.width - start.width - 140) <= 2);
  assert.ok(Math.abs(resized.x - start.x) <= 1, "right-edge resize keeps the left edge fixed");
  assert.ok(await name.evaluate(element => element.clientWidth) > initialNameWidth + 100);
  await page.screenshot({ path: "/private/tmp/voo-layers-width-long-name.png" });
  await handle.focus();
  await page.keyboard.press("ArrowRight");
  assert.ok((await panel.boundingBox()).width > resized.width);
  const committedWidth = Number(await handle.getAttribute("aria-valuenow"));
  const box = await handle.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + 80, box.y + box.height / 2);
  await page.keyboard.press("Escape");
  await page.mouse.up();
  assert.equal(Number(await handle.getAttribute("aria-valuenow")), committedWidth);
  await drag(1000);
  assert.equal(Number(await handle.getAttribute("aria-valuenow")), Number(await handle.getAttribute("aria-valuemax")));
  await handle.press("Home");
  assert.equal(Number(await handle.getAttribute("aria-valuenow")), Number(await handle.getAttribute("aria-valuemin")));
  await handle.dblclick();
  assert.ok(Math.abs((await panel.boundingBox()).width - start.width) <= 1);
  await drag(112);
  const savedWidth = (await panel.boundingBox()).width;
  assert.deepEqual(await page.evaluate(() => window.__vooEditor.serialise()), originalDocument, "chrome resizing must not mutate artwork or history");
  await page.reload();
  await page.waitForLoadState("networkidle");
  await tool("new_document", { width: 600, height: 400, name: "WidthReload", force: true });
  await panel.waitFor();
  await page.waitForFunction(width => Math.abs(document.querySelector('[data-testid="editor-layers-panel"]').getBoundingClientRect().width - width) < 2, savedWidth);
  await panel.locator(".editor-panel-side-swap").click();
  await page.waitForFunction(() => document.querySelector('[data-testid="editor-layers-resize"]').dataset.side === "left");
  const rightDocked = await panel.boundingBox();
  await drag(-64);
  const expandedRight = await panel.boundingBox();
  assert.ok(Math.abs(expandedRight.width - rightDocked.width - 64) <= 2);
  assert.ok(Math.abs(expandedRight.x + expandedRight.width - rightDocked.x - rightDocked.width) <= 1);
  await panel.locator(".editor-panel-side-swap").click();
  await handle.press("Home");
  await drag(savedWidth - Number(await handle.getAttribute("aria-valuemin")));
  await page.screenshot({ path: "/private/tmp/voo-layers-width-desktop.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => getComputedStyle(document.querySelector('[data-testid="editor-layers-resize"]')).display === "none");
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await handle.waitFor();
  assert.ok(Math.abs((await panel.boundingBox()).width - savedWidth) <= 1);
  console.log("Layers width: right-edge drag, keyboard, limits, Escape, reset, reload persistence, responsive layout and document invariance passed.");
});
