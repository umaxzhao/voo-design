// Automated UI audit: drive key editor states through widths x themes x
// locales, then (1) scan generic layout invariants and (2) compare each
// state with its screenshot baseline. Catches layout regressions that
// feature assertions do not look for.
//
//   node tests/e2e/ui-audit.e2e.mjs                 # audit
//   UPDATE_UI_BASELINES=1 node tests/e2e/ui-audit.e2e.mjs   # accept new look
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { withEditorBrowser } from "./editor-browser-fixture.mjs";
import { ACCEPTED_LAYOUT_FINDINGS } from "./ui-audit-accepted.mjs";
import { scanLayout } from "./ui-layout-scanner.mjs";
import { compareScreenshot } from "./ui-screenshot-baseline.mjs";

const WIDTHS = [390, 768, 1440];
const THEMES = ["dark", "light"];
const LOCALES = ["en", "zh"];
// Touch-first widths must keep tappable controls usable (Design.md: 48px goal,
// 44px is the hard platform minimum enforced here).
const TOUCH_WIDTH = 768;
const MIN_TOUCH_TARGET = 44;
const BASELINE_DIR = fileURLToPath(new URL(`./ui-baselines/${process.platform}/`, import.meta.url));
const OUTPUT_DIR = process.env.VOO_UI_AUDIT_OUT || join(tmpdir(), "voo-ui-audit");

const settle = (page) => page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
const waitReady = (page) => page.waitForFunction(() => document.querySelector('[data-testid="design-editor"] [data-open-guard]')
  ?.getAttribute("data-open-guard") === "off");

const select = (page, prefix) => page.evaluate((namePrefix) => {
  const editor = window.__vooEditor;
  editor.setTool("select");
  editor.selectExactly(namePrefix === null ? []
    : editor.getDocument().nodes.filter((node) => node.name.startsWith(namePrefix)).map((node) => node.id));
}, prefix);
// Resizes re-centre the camera and drawers load async content; wait until
// two consecutive frames match so baselines never capture a transition.
// Guest avatars are randomly generated by design, so they are masked.
async function stableScreenshot(page) {
  const options = { animations: "disabled", caret: "hide", mask: [page.locator('[data-testid="profile-avatar"]')] };
  // Park the pointer at the window edge so hover styles and tooltips stay out.
  const { width, height } = page.viewportSize();
  await page.mouse.move(width - 2, Math.round(height / 2));
  let previous = await page.screenshot(options);
  for (let attempt = 0; attempt < 10; attempt += 1) {
    await page.waitForTimeout(120);
    const current = await page.screenshot(options);
    if (current.equals(previous)) return current;
    previous = current;
  }
  throw new Error("UI did not settle within 10 frames");
}
const visible = async (locator) => (await locator.count()) > 0 && locator.first().isVisible();

/**
 * `setup` runs once per state; `enter` runs for every locale/theme/width so
 * transient UI (menus, drawers) is reopened after each resize. `enter`
 * returns false when the state does not exist at that width.
 */
const STATES = [
  { name: "editor-empty", enter: ({ page }) => select(page, null) },
  {
    name: "editor-shape-selected",
    setup: ({ tool }) => tool("build_layout", { nodes: [
      { type: "rect", name: "Audit card", x: 60, y: 60, width: 220, height: 140, fill: "#4F7CFF" },
      { type: "text", name: "Audit title", text: "Quarterly report", x: 60, y: 230, width: 260, height: 40, fontSize: 24 },
    ] }),
    enter: ({ page }) => select(page, "Audit card"),
  },
  { name: "editor-text-selected", enter: ({ page }) => select(page, "Audit title") },
  { name: "editor-multi-selected", enter: ({ page }) => select(page, "Audit") },
  {
    name: "editor-context-menu",
    async enter({ page }) {
      await page.keyboard.press("Escape");
      await select(page, "Audit card");
      await stableScreenshot(page);
      const artboard = await page.locator("[data-editor-artboard]").first().boundingBox();
      if (!artboard) return false;
      await page.mouse.click(artboard.x + artboard.width * 0.5, artboard.y + artboard.height * 0.6, { button: "right" });
      await page.locator('[role="menu"]').first().waitFor({ timeout: 3000 }).catch(() => {});
      return visible(page.locator('[role="menu"]'));
    },
  },
  {
    name: "editor-tool-options-menu",
    async enter({ page }) {
      await page.keyboard.press("Escape");
      const trigger = page.getByTestId("editor-select-menu-trigger");
      if (!(await visible(trigger))) return false;
      await trigger.click();
      await page.waitForTimeout(150);
      return true;
    },
    leave: ({ page }) => page.keyboard.press("Escape"),
  },
  {
    name: "home",
    async setup({ page }) {
      await page.keyboard.press("Escape");
      await page.locator('[data-testid="editor-top-bar"] .app-title-brand-row button').first().click();
      await page.locator(".welcome-dashboard").waitFor();
    },
    enter: async ({ page }) => { await page.keyboard.press("Escape"); return true; },
  },
  {
    name: "home-settings",
    async enter({ page }) {
      await page.keyboard.press("Escape");
      const opener = page.getByRole("button", { name: /^(Settings|设置)$/ });
      if (!(await visible(opener))) return false;
      await opener.first().click();
      await page.getByTestId("settings-drawer").waitFor({ timeout: 3000 });
      return true;
    },
  },
];

const violations = [];
const visualChanges = [];
const created = [];
const skippedStates = [];
let compared = 0;
let maxPassedRatio = 0;

await withEditorBrowser(async ({ page, tool }) => {
  page.setDefaultTimeout(15000);
  await waitReady(page);
  for (const state of STATES) {
    await page.setViewportSize({ width: 1440, height: 1000 });
    await state.setup?.({ page, tool });
    for (const locale of LOCALES) {
      await page.evaluate(async (value) => { const { setLocale } = await import("/src/shared/i18n.js"); await setLocale(value); }, locale);
      for (const theme of THEMES) {
        await page.evaluate(async (value) => {
          const { setEditorTheme } = await import("/src/canvas/use_editor_theme.js");
          setEditorTheme(value);
        }, theme);
        for (const width of WIDTHS) {
          const label = `${state.name}.${locale}.${theme}.${width}`;
          await page.setViewportSize({ width, height: width < TOUCH_WIDTH ? 844 : 1000 });
          await settle(page);
          if (await state.enter({ page, tool }) === false) { skippedStates.push(label); continue; }
          await settle(page);
          await page.waitForTimeout(150);
          const scan = await scanLayout(page, {
            state: label,
            allow: ACCEPTED_LAYOUT_FINDINGS,
            minTouchTarget: width < TOUCH_WIDTH ? MIN_TOUCH_TARGET : 0,
          });
          violations.push(...scan.violations.map((finding) => ({ state: label, ...finding })));
          // Screenshots stay English-only: locale coverage is the scan's job,
          // and fewer baselines keep review of intentional changes cheap.
          if (locale === "en") {
            const shot = await stableScreenshot(page);
            const result = await compareScreenshot(shot, { name: label, baselineDir: BASELINE_DIR, outputDir: OUTPUT_DIR });
            if (result.status === "created") created.push(label);
            else if (result.status === "changed") visualChanges.push(result);
            else { compared += 1; maxPassedRatio = Math.max(maxPassedRatio, result.ratio); }
          }
          await state.leave?.({ page });
        }
      }
    }
  }
});

// Group identical findings so one root cause reads as one line.
const grouped = new Map();
for (const finding of violations) {
  const key = `${finding.kind} | ${finding.target}`;
  const entry = grouped.get(key) ?? { ...finding, states: [] };
  entry.states.push(finding.state);
  grouped.set(key, entry);
}
for (const entry of grouped.values()) {
  process.stdout.write(`LAYOUT ${entry.kind}: ${entry.target}\n  ${entry.detail}\n  in ${entry.states.length} state(s): ${entry.states.slice(0, 4).join(", ")}${entry.states.length > 4 ? ", ..." : ""}\n`);
}
for (const change of visualChanges) {
  process.stdout.write(`VISUAL ${change.name}: ${change.reason}\n  actual ${change.actualPath}${change.diffPath ? `\n  diff   ${change.diffPath}` : ""}\n`);
}
process.stdout.write(`${JSON.stringify({
  layoutIssues: grouped.size, visualChanges: visualChanges.length, screenshotsCompared: compared, maxPassedRatio, statesNotApplicable: skippedStates,
  baselinesCreated: created.length, outputDir: OUTPUT_DIR,
})}\n`);
if (grouped.size || visualChanges.length) process.exitCode = 1;
